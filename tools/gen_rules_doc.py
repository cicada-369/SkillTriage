#!/usr/bin/env python3
"""Generate docs/RULES.md from the rule registry.

Run after adding or changing a rule:

    python tools/gen_rules_doc.py

CI runs with ``--check`` so the checked-in catalog cannot drift.
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from skilltriage.models import AST_NAMES, OWASP_URL  # noqa: E402
from skilltriage.rules import all_rules  # noqa: E402

DEFAULT_OUTPUT = ROOT / "docs" / "RULES.md"


def render() -> str:
    rules = sorted(all_rules(), key=lambda rule: (rule.ast, rule.id))
    counts = Counter(rule.ast for rule in rules)
    lines: list[str] = [
        "# Rule catalog",
        "",
        "Generated from the rule registry by `python tools/gen_rules_doc.py`.",
        "Do not edit this file by hand; edit the rule modules and regenerate.",
        "",
        f"- **Rules:** {len(rules)}",
        f"- **Taxonomy:** [OWASP Agentic Skills Top 10]({OWASP_URL})",
        f"- **AST controls:** {len([ast for ast in AST_NAMES if counts.get(ast)])} of 10",
        "",
        "Severity and confidence are the *base* values. Context scoring can lower",
        "both when a match appears in documentation, an example fence, a warning",
        "sentence, a comment, or a security-tool/test file. Findings are never",
        "silently dropped.",
        "",
        "## Summary",
        "",
        "| AST | Risk | Rules |",
        "|---|---|---:|",
    ]
    for ast in sorted(AST_NAMES):
        lines.append(f"| **{ast}** | {AST_NAMES[ast]} | {counts.get(ast, 0)} |")

    for ast in sorted(AST_NAMES):
        group = [rule for rule in rules if rule.ast == ast]
        if not group:
            continue
        lines.extend(
            [
                "",
                f"## {ast} — {AST_NAMES[ast]}",
                "",
                "| Rule | Severity | Confidence | Title |",
                "|---|---|---|---|",
            ]
        )
        for rule in group:
            lines.append(
                f"| `{rule.id}` | {rule.severity.value} | {rule.confidence.value} | {rule.title} |"
            )
        lines.append("")
        for rule in group:
            lines.extend(
                [
                    f"### `{rule.id}` — {rule.title}",
                    "",
                    f"- **Severity:** {rule.severity.value}",
                    f"- **Confidence:** {rule.confidence.value}",
                    f"- **Description:** {rule.description}",
                    f"- **Remediation:** {rule.remediation}",
                ]
            )
            if rule.cwes:
                lines.append(f"- **CWE:** {', '.join(rule.cwes)}")
            if rule.tags:
                lines.append(f"- **Tags:** {', '.join(rule.tags)}")
            lines.append("")

    lines.extend(
        [
            "---",
            "",
            "The AST identifiers are from the OWASP Agentic Skills Top 10 project.",
            "The descriptions here are skilltriage's own; see `NOTICE` for attribution.",
            "",
        ]
    )
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if docs/RULES.md is stale")
    parser.add_argument("--output", default=str(DEFAULT_OUTPUT), help="output path")
    args = parser.parse_args(argv)

    content = render()
    output = Path(args.output)
    if args.check:
        if not output.is_file():
            print(f"missing rule catalog: {output}", file=sys.stderr)
            return 1
        current = output.read_text(encoding="utf-8")
        if current != content:
            print(
                f"{output} is stale; run: python tools/gen_rules_doc.py",
                file=sys.stderr,
            )
            return 1
        print(f"{output} is up to date")
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")
    print(f"wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
